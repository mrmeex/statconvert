def test_selected_workbook_object_exports_selected_schema(
    tmp_path: Path,
) -> None:
    workbook = tmp_path / "book.xlsx"
    output = tmp_path / "data.toml"
    with pd.ExcelWriter(workbook) as writer:
        pd.DataFrame({"DataId": [1]}).to_excel(
            writer,
            sheet_name="Data",
            index=False,
        )
        pd.DataFrame({"LookupCode": ["A"]}).to_excel(
            writer,
            sheet_name="Lookup",
            index=False,
        )

    result = runner.invoke(
        app,
        [
            "schema",
            str(workbook),
            "--object",
            "Data",
            "--export-contract",
            str(output),
        ],
    )

    assert result.exit_code == 0
    assert [column.name for column in load_contract(output).columns] == [
        "DataId"
    ]


