def test_build_exported_contract_uses_conservative_defaults() -> None:
    dataset = Dataset(
        pd.DataFrame(
            {
                "id": [1, 2],
                "optional": ["value", None],
            }
        )
    )

    contract = build_schema_contract(dataset, "people.csv")

    assert contract.contract_version == 1
    assert contract.name == "people schema contract"
    assert contract.description == (
        "Generated by StatConvert from resolved dataset schema and metadata."
    )
    assert contract.dataset.require_columns is True
    assert contract.dataset.allow_extra_columns is False
    assert contract.dataset.column_order == "ignore"
    assert [column.name for column in contract.columns] == ["id", "optional"]
    assert contract.columns[0].storage_type == "int64"
    assert contract.columns[0].logical_type == "integer"
    assert contract.columns[0].nullable is False
    assert contract.columns[1].logical_type == "string"
    assert contract.columns[1].nullable is True
    assert all(column.required for column in contract.columns)
    assert all(column.allowed_values is None for column in contract.columns)
    assert all(column.min_value is None for column in contract.columns)
    assert all(column.max_value is None for column in contract.columns)
    assert all(column.regex is None for column in contract.columns)
    assert all(column.unique is False for column in contract.columns)


def test_contract_toml_is_deterministic_and_round_trips() -> None:
    dataset = Dataset(pd.DataFrame({"id": [1], "name": ["Ada"]}))
    contract = build_schema_contract(dataset, "people.csv")

    first = contract_to_toml(contract)
    second = contract_to_toml(contract)
    parsed = tomllib.loads(first)

    assert first == second
    assert parsed["contract_version"] == 1
    assert parsed["dataset"] == {
        "require_columns": True,
        "allow_extra_columns": False,
        "column_order": "ignore",
    }
    assert [column["name"] for column in parsed["columns"]] == ["id", "name"]
    assert "unique" not in first
    assert "allowed_values" not in first
    assert "\nmin =" not in first
    assert "\nmax =" not in first
    assert "\nregex =" not in first


def test_exported_contract_parses_and_validates_source_dataset(
    tmp_path: Path,
) -> None:
    dataset = Dataset(
        pd.DataFrame(
            {
                "id": [1, 2],
                "name": ["Ada", "Grace"],
            }
        )
    )
    source = tmp_path / "people.csv"
    output = tmp_path / "people.toml"

    written = export_schema_contract(dataset, source, output)
    contract = load_contract(written)
    result = validate_contract(dataset, contract)

    assert written == output
    assert result.valid is True
    assert output.read_text(encoding="utf-8").startswith(
        'contract_version = 1\nname = "people schema contract"\n'
    )


def test_contract_build_does_not_modify_dataset() -> None:
    dataset = _resolved_dataset()
    dataframe_before = dataset.dataframe.copy(deep=True)
    metadata_before = copy.deepcopy(dataset.normalized_metadata)
    columns_before = copy.deepcopy(dataset.column_metadata)

    build_schema_contract(dataset, "source.csv")

    pd.testing.assert_frame_equal(dataset.dataframe, dataframe_before)
    assert dataset.normalized_metadata == metadata_before
    assert dataset.column_metadata == columns_before


def test_export_collision_requires_overwrite_contract(
    tmp_path: Path,
) -> None:
    dataset = Dataset(pd.DataFrame({"id": [1]}))
    source = tmp_path / "data.csv"
    output = tmp_path / "schema.toml"
    output.write_text("old", encoding="utf-8")

    with pytest.raises(
        OutputPathError,
        match="Schema contract already exists",
    ):
        export_schema_contract(dataset, source, output)

    export_schema_contract(dataset, source, output, overwrite=True)
    assert load_contract(output).columns[0].name == "id"


