def test_schema_command_collision_and_overwrite(tmp_path: Path) -> None:
    source = _write_csv(tmp_path)
    output = tmp_path / "schema.toml"
    command = [
        "schema",
        str(source),
        "--export-contract",
        str(output),
    ]

    assert runner.invoke(app, command).exit_code == 0
    collision = runner.invoke(app, command)
    overwritten = runner.invoke(app, [*command, "--overwrite-contract"])

    assert collision.exit_code == 1
    assert "Schema contract already exists" in collision.output
    assert "Use --overwrite-contract" in collision.output
    assert overwritten.exit_code == 0


