def test_sidecar_wins_over_embedded_parquet_export_types(
    tmp_path: Path,
) -> None:
    source = tmp_path / "precedence.parquet"
    output = tmp_path / "precedence.toml"
    ArrowBackend().write(_resolved_dataset(), source)
    sidecar = Dataset.sidecar_path(source)
    payload = json.loads(sidecar.read_text(encoding="utf-8"))
    payload["columns"][0]["physical_type"] = "int16"
    payload["columns"][0]["logical_type"] = "sidecar_identifier"
    sidecar.write_text(json.dumps(payload), encoding="utf-8")

    result = runner.invoke(
        app,
        [
            "schema",
            str(source),
            "--export-contract",
            str(output),
        ],
    )

    contract = load_contract(output)
    assert result.exit_code == 0
    assert contract.columns[0].storage_type == "int16"
    assert contract.columns[0].logical_type == "sidecar_identifier"


def _write_csv(tmp_path: Path) -> Path:
    source = tmp_path / "people.csv"
    pd.DataFrame(
        {
            "id": [1, 2],
            "status": ["active", "inactive"],
        }
    ).to_csv(source, index=False)
    return source


def _resolved_dataset() -> Dataset:
    metadata = DatasetMetadata(
        source_format="sav",
        source_backend="pyreadstat",
    )
    metadata.add_variable(
        VariableMetadata(
            name="id",
            storage_type="int32",
        )
    )
    metadata.add_variable(
        VariableMetadata(
            name="status",
            storage_type="string",
        )
    )
    return Dataset(
        dataframe=pd.DataFrame(
            {
                "id": [1, 2],
                "status": ["active", "inactive"],
            }
        ),
        source_format="sav",
        normalized_metadata=metadata,
        column_metadata={
            "id": ColumnMetadata(
                name="id",
                physical_type="int32",
                logical_type="identifier",
            ),
            "status": ColumnMetadata(
                name="status",
                physical_type="string",
                logical_type="string",
            ),
        },
    )
